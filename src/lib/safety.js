const normalize = (s) => String(s || '').replace(/[֑-ׇ]/g, '').replace(/\s+/g, ' ').trim();

export function screen(text) {
  const t = normalize(text);
  const hits = [];
  for (const rule of RULES) {
    if (rule.patterns.some((p) => p.test(t))) hits.push({ kind: rule.kind, notice: rule.notice });
  }
  const kinds = hits.map((h) => h.kind);
  const level = kinds.includes('crisis') ? 'crisis' : kinds.includes('emergency') ? 'emergency' : hits.length ? 'caution' : 'none';
  return { level, hits };
}

// במצב חירום או מצוקה לא פונים למודל. מחזירים תשובה קבועה.
export function blockingReply(result) {
  if (result.level === 'crisis') {
    return 'אני שומעת שקשה לך עכשיו. את זה לא כדאי להחזיק לבד. ער"ן זמינים בכל שעה בטלפון 1201, ואפשר גם בצ׳אט באתר שלהם. אם יש סכנה מיידית, התקשר או התקשרי עכשיו למד"א 101 או ל-112.';
  }
  if (result.level === 'emergency') {
    return 'מה שתיארת הוא סימן אזהרה שמחייב פנייה לרופא מיד, ולא שיחה על איורוודה. במצב חירום: מד"א 101 או 112. אם אפשר, פנו היום לרופא המשפחה או למוקד רפואי.';
  }
  return null;
}

// תוספת להנחיית המערכת לפי מה שהמסנן מצא, כדי שהמודל יידע מה כבר הוצג.
export function safetyAddendum(result) {
  if (!result.hits.length) return '';
  const lines = result.hits.map((h) => `- ${h.kind}: ${h.notice}`);
  return `\n\nהמסנן האוטומטי זיהה בהודעה האחרונה את הנושאים הבאים, וההודעה המתאימה כבר הוצגה למשתמש:\n${lines.join('\n')}\nאל תחזרי על ההודעה מילה במילה. הקפידי על הגבול שהיא מתארת.`;
}
